let LOCALE = 'en';

function currentFleetLang() { return (window.CarinoLang && window.CarinoLang.current) || 'en'; }

function t(key) {
    const dict = I18N[LOCALE];
    return (dict && dict[key]) || key;
}

// Static markup: elements carrying data-i18n use their original English text as
// the key (captured on first pass — with whitespace runs collapsed so multi-line
// markup still matches — so locale switches stay reversible).
function applyStaticI18n() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
        if (!el.dataset.i18nKey) el.dataset.i18nKey = el.textContent.trim().replace(/\s+/g, ' ');
        el.textContent = t(el.dataset.i18nKey);
    });
}

// Prominent title / placeholder attributes, addressed explicitly by element —
// the map values are the English keys, so re-applying is always idempotent.
const I18N_PLACEHOLDERS = {
    csInput: 'seconds, e.g. -1.25',
    cdSearch: 'Search events…',
    evName: 'e.g. Project launch',
    zoneSearch: 'Search cities / timezones…',
    wbInput: 'Paste any timestamp — epoch, ISO 8601 / RFC 3339, DICOM DA/DT, or SMPTE HH:MM:SS:FF',
    tmMin: 'min',
    tmSec: 'sec',
};
const I18N_TITLES = {
    clockSrc: 'All times on this page — clocks, markets, countdowns, calendar, workbench — derive from this clock. Adjust it if this device\'s clock drifts.',
    utTick: 'Tick sound each second — session-only; audio can never auto-start on load',
    utMet: 'Metronome',
    utTimer: 'Timer',
    utCal: 'Calendar',
    toggleHours: 'Show nominal hour-zone limits — real zones deviate politically',
    openZoneSearch: 'Search all time zones',
    wbNow: 'Track the current instant',
    wbRate: 'SMPTE frame rate',
    metDown: 'Slower',
    metUp: 'Faster',
};
function applyAttrI18n() {
    Object.keys(I18N_PLACEHOLDERS).forEach((id) => {
        const el = document.getElementById(id);
        if (el) el.placeholder = t(I18N_PLACEHOLDERS[id]);
    });
    Object.keys(I18N_TITLES).forEach((id) => {
        const el = document.getElementById(id);
        if (el) el.title = t(I18N_TITLES[id]);
    });
    const mkKicker = document.querySelector('.now-mk-row .kicker');
    if (mkKicker) mkKicker.title = t('Nominal session hours — public holidays are not accounted for');
    // The 12h/24h toggle is rewritten by app code; translate it only while its
    // text is still a known English key (first load), never guess otherwise.
    const ft = document.getElementById('fmtToggle');
    if (ft && (ft.textContent.trim() === '24-hour' || ft.textContent.trim() === '12-hour')) {
        ft.textContent = t(ft.textContent.trim());
    }
}

function applyAll() {
    const l = currentFleetLang();
    LOCALE = (l === 'en' || I18N[l]) ? l : 'en';
    document.documentElement.lang = LOCALE;
    applyStaticI18n();
    applyAttrI18n();
    // Surfaces the app renders once, from the inline script, before this
    // deferred file has executed (the clock-source line, the Now readout grid).
    // They cannot translate themselves, so index.html registers a repaint here.
    if (typeof window.onLanguageApplied === 'function') window.onLanguageApplied();
}

window.CarinoI18n = { t: t, apply: applyAll };

// carino-lang.js is deferred and executes before this (also deferred, later in
// the document) script, so CarinoLang exists by DOMContentLoaded.
document.addEventListener('DOMContentLoaded', applyAll);
window.addEventListener('carino:langchange', applyAll);
